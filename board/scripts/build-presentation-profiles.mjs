import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { format } from 'prettier';

import { TOKEN_KEYS, validateRegistry } from './presentation-contract.mjs';

const BOARD_ROOT = fileURLToPath(new URL('..', import.meta.url));
const REGISTRY_PATH = path.join(BOARD_ROOT, 'presentation', 'profiles.json');
const CSS_PATH = path.join(BOARD_ROOT, 'static', 'presentation-profiles.css');
const REGISTRY_JS_PATH = path.join(BOARD_ROOT, 'static', 'presentation-registry.js');

function cssTokenName(token) {
  return `--dpp-${token.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()}`;
}

function formatCssColorLiterals(value) {
  return value.replace(/#([0-9a-f]{8}|[0-9a-f]{6})(?![0-9a-f])/gi, (_match, hex) => {
    const normalized = hex.toLowerCase();
    const pairs = normalized.match(/.{2}/g);
    const canShorten = pairs.every((pair) => pair[0] === pair[1]);
    return canShorten ? `#${pairs.map((pair) => pair[0]).join('')}` : `#${normalized}`;
  });
}

function renderProfileBlock(profile, isDefault) {
  const selector = isDefault
    ? `:root,\n:root[data-dpp-theme='${profile.id}']`
    : `:root[data-dpp-theme='${profile.id}']`;
  const declarations = [
    `  color-scheme: ${profile.colorScheme};`,
    '',
    ...TOKEN_KEYS.map(
      (token) => `  ${cssTokenName(token)}: ${formatCssColorLiterals(profile.tokens[token])};`,
    ),
  ];
  return `${selector} {\n${declarations.join('\n')}\n}`;
}

export function renderProfilesCss(registry) {
  const blocks = registry.profiles.map((profile) =>
    renderProfileBlock(profile, profile.id === registry.defaultProfileId),
  );
  return [
    '/* Generated by scripts/build-presentation-profiles.mjs. Do not edit directly. */',
    '',
    ...blocks.flatMap((block, index) => (index === blocks.length - 1 ? [block] : [block, ''])),
    '',
  ].join('\n');
}

export function renderRegistryJs(registry) {
  const publicRegistry = {
    schemaVersion: registry.schemaVersion,
    defaultProfileId: registry.defaultProfileId,
    storageKey: registry.storageKey,
    paletteRevision: registry.paletteRevision,
    paletteNote: registry.paletteNote,
    profiles: registry.profiles.map(({ tokens: _tokens, ...profile }) => profile),
  };
  const serialized = JSON.stringify(publicRegistry, null, 2);
  return `/* Generated by scripts/build-presentation-profiles.mjs. Do not edit directly. */
(() => {
  'use strict';

  const registry = JSON.parse(\`${serialized}\`);

  function deepFreeze(value) {
    for (const child of Object.values(value)) {
      if (child && typeof child === 'object') deepFreeze(child);
    }
    return Object.freeze(value);
  }

  Object.defineProperty(window, 'DPP_PRESENTATION_REGISTRY', {
    value: deepFreeze(registry),
    configurable: false,
    enumerable: true,
    writable: false,
  });
})();
`;
}

async function readRegistry() {
  return validateRegistry(JSON.parse(await readFile(REGISTRY_PATH, 'utf8')));
}

async function checkFile(filePath, expected) {
  try {
    return (await readFile(filePath, 'utf8')) === expected;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

async function main() {
  const registry = await readRegistry();
  const formattedCss = await format(renderProfilesCss(registry), {
    parser: 'css',
    printWidth: 110,
    semi: true,
    singleQuote: true,
    tabWidth: 2,
  });
  const outputs = [
    [CSS_PATH, formattedCss],
    [REGISTRY_JS_PATH, renderRegistryJs(registry)],
  ];

  if (process.argv.includes('--check')) {
    const results = await Promise.all(outputs.map(([filePath, content]) => checkFile(filePath, content)));
    const stale = outputs.filter((_output, index) => !results[index]).map(([filePath]) => path.relative(BOARD_ROOT, filePath));
    if (stale.length) {
      throw new Error(
        `Generated presentation assets are stale: ${stale.join(', ')}. Run npm run build:presentation.`,
      );
    }
    process.stdout.write('Generated presentation assets are current.\n');
    return;
  }

  await mkdir(path.dirname(CSS_PATH), { recursive: true });
  await Promise.all(outputs.map(([filePath, content]) => writeFile(filePath, content)));
  process.stdout.write(`Generated ${outputs.length} presentation assets.\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.stack ?? error.message}\n`);
  process.exitCode = 1;
});
